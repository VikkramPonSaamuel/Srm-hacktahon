from datetime import datetime
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, ConfigDict, Field, field_validator

from app.core.sanitizer import sanitize_data


class IncidentEventBase(BaseModel):
    event_type: str = Field(
        ...,
        max_length=50,
        description="Event kind: detected, analyzed, recovery_attempted, status_changed, note_added, resolved",
    )
    timestamp: datetime = Field(..., description="UTC timestamp of the incident event")
    details: Optional[Dict[str, Any]] = Field(default=None, description="Sanitized contextual event metadata")
    correlation_id: Optional[str] = Field(default=None, max_length=64, description="Correlation identifier")

    @field_validator("details", mode="before")
    @classmethod
    def sanitize_event_details(cls, v: Any) -> Any:
        return sanitize_data(v) if v is not None else None


class IncidentEventCreate(IncidentEventBase):
    pass


class IncidentEventResponse(IncidentEventBase):
    model_config = ConfigDict(from_attributes=True)

    id: int
    incident_id: int
    stage: Optional[str] = Field(default=None, description="Normalized lifecycle stage")
    created_at: datetime
    updated_at: datetime


class IncidentBase(BaseModel):
    journey_execution_id: Optional[int] = Field(default=None, description="Related journey execution ID")
    step_execution_id: Optional[int] = Field(default=None, description="Failed step execution ID")
    journey_id: Optional[int] = Field(default=None, description="Parent business journey ID")
    service_name: Optional[str] = Field(default=None, max_length=100, description="Affected component or service name")
    incident_type: str = Field(
        default="transaction_failure",
        max_length=50,
        description="Type: transaction_failure, latency_spike, auth_breakdown, service_degradation",
    )
    module: Optional[str] = Field(
        default=None,
        description="Origin module: transaction_reliability, brand_impersonation, website_security",
    )
    severity: str = Field(
        ...,
        max_length=20,
        description="Severity level: low, medium, high, critical",
    )
    title: str = Field(..., max_length=200, description="Concise summary title of the failure incident")
    description: str = Field(..., description="Detailed description of the observed anomaly")
    status: str = Field(
        default="open",
        max_length=30,
        description="Status: open, investigating, mitigated, resolved, closed",
    )
    failure_category: Optional[str] = Field(default=None, max_length=50, description="Category of failure")
    root_cause_hypothesis: Optional[str] = None
    resolution_summary: Optional[str] = None
    recovery_status: str = Field(
        default="not_started",
        max_length=30,
        description="Recovery status: not_started, in_progress, recovered, failed",
    )
    recovery_duration_ms: Optional[float] = Field(default=None, ge=0, description="Execution duration of recovery action")
    detected_at: datetime = Field(..., description="UTC timestamp when the incident was detected")
    resolved_at: Optional[datetime] = Field(default=None, description="UTC timestamp when resolved")
    is_demo: bool = Field(default=False, description="Flag indicating synthetic demonstration incident")

    @field_validator("description", mode="before")
    @classmethod
    def sanitize_description_field(cls, v: Any) -> Any:
        return sanitize_data(v) if v is not None else None


class IncidentCreate(IncidentBase):
    incident_id: Optional[str] = Field(default=None, max_length=64, description="Optional custom incident ID (autogenerated if omitted)")
    initial_event: Optional[IncidentEventCreate] = Field(default=None, description="Optional initial detection event")


class IncidentUpdate(BaseModel):
    status: Optional[str] = Field(default=None, max_length=30)
    severity: Optional[str] = Field(default=None, max_length=20)
    root_cause_hypothesis: Optional[str] = None
    resolution_summary: Optional[str] = None
    recovery_status: Optional[str] = Field(default=None, max_length=30)
    recovery_duration_ms: Optional[float] = Field(default=None, ge=0)
    resolved_at: Optional[datetime] = None


class IncidentResponse(IncidentBase):
    model_config = ConfigDict(from_attributes=True)

    id: int
    incident_id: str
    created_at: datetime
    updated_at: datetime


class IncidentDetailResponse(IncidentResponse):
    events: List[IncidentEventResponse] = Field(default_factory=list, description="Timeline history of incident events")


class RetryRecoveryRequest(BaseModel):
    operator_override: bool = Field(default=False, description="Whether to override cooldowns and retry limits")
    notes: Optional[str] = Field(None, description="Operator notes for audit trail")


class EscalateIncidentRequest(BaseModel):
    reason: str = Field(..., max_length=200, description="Escalation rationale")
    notes: Optional[str] = Field(None, description="Additional context or handover instructions")
