from datetime import datetime
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, ConfigDict, Field, field_validator

from app.core.sanitizer import sanitize_data


class StepExecutionBase(BaseModel):
    journey_step_id: Optional[int] = Field(default=None, description="Associated journey step ID")
    status: str = Field(..., max_length=30, description="Step run status: pending, running, success, failed, skipped, timed_out")
    started_at: datetime = Field(..., description="UTC start timestamp")
    completed_at: Optional[datetime] = Field(default=None, description="UTC completion timestamp")
    duration_ms: Optional[float] = Field(default=None, ge=0, description="Total execution duration in milliseconds")
    latency_ms: Optional[float] = Field(default=None, ge=0, description="Network or service response latency")
    http_status: Optional[int] = Field(default=None, description="HTTP status code received, if applicable")
    error_code: Optional[str] = Field(default=None, max_length=100, description="Sanitized system error code")
    failure_category: Optional[str] = Field(
        default=None,
        max_length=50,
        description="Category: network_timeout, auth_failure, validation_error, service_unavailable, database_deadlock, rate_limited",
    )
    retry_count: int = Field(default=0, ge=0, description="Number of retries attempted")
    diagnostic_data: Optional[Dict[str, Any]] = Field(default=None, description="Sanitized diagnostic context payload")

    @field_validator("diagnostic_data", mode="before")
    @classmethod
    def sanitize_diagnostics(cls, v: Any) -> Any:
        return sanitize_data(v) if v is not None else None


class StepExecutionCreate(StepExecutionBase):
    pass


class StepExecutionResponse(StepExecutionBase):
    model_config = ConfigDict(from_attributes=True)

    id: int
    journey_execution_id: int
    created_at: datetime
    updated_at: datetime


class JourneyExecutionBase(BaseModel):
    journey_id: Optional[int] = Field(default=None, description="Target journey ID")
    correlation_id: str = Field(..., max_length=64, description="Distributed correlation trace ID")
    environment: str = Field(default="development", max_length=30, description="Execution environment")
    status: str = Field(
        default="in_progress",
        max_length=30,
        description="Status: pending, in_progress, success, failed, partially_recovered",
    )
    started_at: datetime = Field(..., description="UTC execution start timestamp")
    completed_at: Optional[datetime] = Field(default=None, description="UTC execution completion timestamp")
    duration_ms: Optional[float] = Field(default=None, ge=0, description="Total journey execution duration in milliseconds")
    is_demo: bool = Field(default=False, description="Flag indicating synthetic demonstration data")


class JourneyExecutionCreate(JourneyExecutionBase):
    execution_id: Optional[str] = Field(default=None, max_length=64, description="Optional custom execution ID (autogenerated if omitted)")
    steps: Optional[List[StepExecutionCreate]] = Field(default=None, description="Optional step execution batch")


class JourneyExecutionUpdate(BaseModel):
    status: Optional[str] = Field(default=None, max_length=30)
    completed_at: Optional[datetime] = None
    duration_ms: Optional[float] = Field(default=None, ge=0)


class JourneyExecutionResponse(JourneyExecutionBase):
    model_config = ConfigDict(from_attributes=True)

    id: int
    execution_id: str
    created_at: datetime
    updated_at: datetime


class JourneyExecutionDetailResponse(JourneyExecutionResponse):
    step_executions: List[StepExecutionResponse] = Field(default_factory=list, description="Ordered step execution results")
